// Test hàm thuần của tìm kiếm (không cần trình duyệt). Chạy: node tools/search_test.mjs
import fs from 'fs';
const html = fs.readFileSync('E:/Your English/index.html', 'utf8').split('\r\n').join('\n');
const app = html.match(/<script type="text\/plain" id="appSrc">([\s\S]*?)<\/script>/)[1];
const mod = app.includes('/*SEARCH-BEGIN*/')
  ? app.slice(app.indexOf('/*SEARCH-BEGIN*/'), app.indexOf('/*SEARCH-END*/'))
  : fs.readFileSync('E:/Your English/tools/search_module.js', 'utf8');
const a0 = html.indexOf('const ALL = (window.__PASSAGES');
const a1 = html.indexOf('\n];', a0) + 3;
const allSrc = html.slice(a0, a1);
const TOPICS = [['family', 'Family'], ['friends', 'Friends'], ['school', 'School'], ['work', 'Work'], ['lifestyle', 'Lifestyle'], ['health', 'Health'], ['tech', 'Tech']].map(([k, label]) => ({ k, label }));
TOPICS.push({ k: 'stories', label: 'Stories' });
const STORIES = [{ id: 'story-ussr', title: 'The Fall of the Soviet Union', level: 'B1' }];
const { Search, ALL, SEARCH_TAGS } = new Function('window', allSrc + '\n' + mod + '\nreturn {Search,ALL,SEARCH_TAGS};')({});
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const idx = Search.buildIndex({ lessons: ALL, stories: STORIES, topics: TOPICS });
const S = (q, o) => Search.search(idx, q, o);
const top = (r, kind) => ((r[kind][0] || {}).title || (r[kind][0] || {}).label);
ok(ALL.filter(p => p.id > 0).every(p => SEARCH_TAGS[p.id]), 'mọi bài (9) đều có tag mẫu');
ok(top(S('gia dinh'), 'topics') === 'Family', 'không dấu: "gia dinh" → Family (' + top(S('gia dinh'), 'topics') + ')');
ok(top(S('gia đình'), 'topics') === 'Family' && top(S('gia dinh'), 'lessons') === 'My Family', 'có dấu = không dấu; bài "My Family" đứng đầu');
ok(top(S('familly'), 'topics') === 'Family', 'sai chính tả nhẹ: "familly" → Family');
ok(top(S('fmaily'), 'topics') === 'Family', 'hoán vị: "fmaily" → Family');
ok(top(S('fam'), 'topics') === 'Family', 'gõ dở: "fam" → Family');
ok(top(S('parents'), 'lessons') === 'My Family', 'đồng nghĩa: "parents" → My Family');
ok(top(S('ba me'), 'lessons') === 'My Family', 'tiếng Việt: "ba me" → My Family');
ok(top(S('cong nghe'), 'topics') === 'Tech' && top(S('cong nghe'), 'lessons') === 'Technology In Our Life', '"cong nghe" → Tech + bài công nghệ');
ok(top(S('smartphone'), 'lessons') === 'Technology In Our Life', '"smartphone" → bài công nghệ');
ok(top(S('cuoi tuan'), 'lessons') === 'My Weekend', '"cuoi tuan" → My Weekend');
ok(top(S('job'), 'lessons') === 'Love what you do', '"job" → Love what you do (' + top(S('job'), 'lessons') + ')');
ok(top(S('job interview'), 'tags') == null || true, 'không lỗi với cụm không có tag');
ok(top(S('lich su'), 'lessons') === 'The Fall of the Soviet Union' && S('lich su').lessons[0].story, '"lich su" → Story Liên Xô (đánh dấu story)');
ok(top(S('soviet'), 'lessons') === 'The Fall of the Soviet Union', '"soviet" → Story');
ok(top(S('daily routine'), 'tags') === 'daily routine' && S('daily routine').tags[0].ids.length >= 3, 'tag "daily routine" gom ≥3 bài');
ok(Search.byTag(idx, 'sit:daily routine').length >= 3, 'byTag trả danh sách id');
ok(top(S('my family'), 'lessons') === 'My Family', 'khớp tiêu đề xếp trên khớp tag');
ok(S('').lessons.length === 0 && S('   ').topics.length === 0, 'chuỗi rỗng → không kết quả');
ok(S('zzzzqq').lessons.length + S('zzzzqq').topics.length + S('zzzzqq').tags.length === 0, 'từ vô nghĩa → không kết quả');
ok(S('xyz1').topics.length === 0, 'không nhiễu: "xyz1" không ra chủ đề');
const r = S('l'); ok(r.topics.length + r.lessons.length <= 8, 'một chữ cái: số kết quả bị chặn ≤ 8');
ok(S('school').lessons.length <= 5 && S('school').lessons.length >= 2, '"school" ra ≥2 bài, ≤5');
const rd = S('school', { read: new Set([3]) }); ok(rd.lessons[0].id !== 3 || S('school').lessons[0].id === 3, 'hoà điểm: bài chưa đọc lên trước (' + rd.lessons.map(x => x.id).join(',') + ')');
ok(Search.popularTags(idx, 6, 'sit').length === 6 && Search.popularTags(idx, 6, 'sit')[0].ids.length >= 3, 'tag phổ biến: sắp theo số bài');
const t0 = process.hrtime.bigint(); for (let i = 0; i < 200; i++) S('gia dinh'); const ms = Number(process.hrtime.bigint() - t0) / 1e6 / 200;
ok(ms < 3, 'tốc độ: ' + ms.toFixed(2) + ' ms/lượt (9 bài)');
const big = { lessons: [], topics: TOPICS, stories: [] }; for (let i = 0; i < 500; i++) big.lessons.push(Object.assign({}, ALL[1 + (i % 9)], { id: 1000 + i }));
const bi = Search.buildIndex(big); const t1 = process.hrtime.bigint(); for (let i = 0; i < 20; i++) Search.search(bi, 'gia dinh'); const ms2 = Number(process.hrtime.bigint() - t1) / 1e6 / 20;
ok(ms2 < 40, 'quy mô 500 bài: ' + ms2.toFixed(1) + ' ms/lượt');
console.log(fails ? fails + ' FAIL' : 'ALL PASS'); process.exit(fails ? 1 : 0);
