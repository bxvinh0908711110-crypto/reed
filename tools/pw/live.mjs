import { chromium, devices } from 'playwright'; import http from 'http'; import fs from 'fs';
const types={'.svg':'image/svg+xml','.html':'text/html'};
const srv=http.createServer((q,r)=>{const u=decodeURIComponent(q.url.split('?')[0]).replace(/^\//,'');try{const e=u.slice(u.lastIndexOf('.'));if(types[e])r.setHeader('Content-Type',types[e]);r.end(fs.readFileSync('E:/Your English/'+u))}catch{r.statusCode=404;r.end()}}).listen(8785);
const b=await chromium.launch(); const ctx=await b.newContext({...devices['iPhone 13']}); const p=await ctx.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>m.type()==='error'&&errs.push(m.text()));
await p.goto('http://localhost:8785/index.html'); await p.waitForTimeout(5500);
console.log('remote:',await p.evaluate(()=>!!window.__PASSAGES), 'ALL:',await p.evaluate(()=>ALL.map(l=>l.cat+':'+l.topic)));
console.log('soon topics:',await p.evaluate(()=>[...document.querySelectorAll('#topics button[data-soon]')].map(b=>b.dataset.k)));
console.log('errors',errs);
await b.close(); srv.close();
